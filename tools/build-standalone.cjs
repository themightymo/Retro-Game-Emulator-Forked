// Builds standalone/index.html from shortcode-template.php and standalone/page-template.html,
// so the standalone page always matches the plugin's player markup.
// Run with: node tools/build-standalone.cjs          (writes the file)
//           node tools/build-standalone.cjs --check  (exits 1 if the file is out of date)
const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const output = 'standalone/index.html';

const escape = text => text.replace(/[&<>"']/g, c => ({'&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#039;'}[c]));
const phpString = "'((?:[^'\\\\]|\\\\.)*)'";
const unquote = text => text.replace(/\\(.)/g, '$1');

// Each replacement must match, so a template change the build doesn't understand fails loudly
// instead of silently producing a stale or broken page.
function replace(html, pattern, replacement, label) {
	if (!pattern.test(html)) throw new Error('shortcode-template.php: could not find ' + label + '. Update tools/build-standalone.cjs to match the template.');
	return html.replace(pattern, replacement);
}

function player() {
	let html = read('shortcode-template.php');
	html = replace(html, /^<\?php if \(! defined\('ABSPATH'\)\) \{ exit; \} \?>\n/, '', 'the ABSPATH guard');
	// The plugin lists the site's ROMs; the standalone page lists the browser's library.
	// A new id keeps app.js from treating the library's options as ROM URLs.
	html = replace(html, /retro-game-emulator-game-select/g, 'rge-library-select', 'the game select id');
	html = replace(html, /\s*<\?php foreach \(\$romsArray as \$rom\) : \?>[\s\S]*?<\?php endforeach; \?>/, '', 'the ROM option loop');
	html = replace(html, /<\?php if \(current_user_can\('manage_options'\) && current_user_can\('upload_files'\)\) : \?>\s*<button type="button" class="rge-upload retro-game-upload-roms">[\s\S]*?<\?php endif; \?>/,
		'<button type="button" class="rge-remove" disabled>Remove</button>\n' +
		'        <button type="button" class="rge-upload rge-open">+ Open ROMs</button>\n' +
		'        <input type="file" class="rge-file" accept=".nes" multiple>', 'the upload button');
	html = replace(html, /(\n\s*)<div class="rge-player">/, '$1<p class="rge-library-note" role="status" aria-live="polite"></p>$1<div class="rge-player">', 'the player wrapper');
	html = replace(html, /<p><\?php echo empty\(\$romsArray\)[^>]*\?><\/p>/,
		'<p class="rge-empty-text">Open a .nes ROM from your computer, or drop one onto this page. Games you open are saved in this browser only.</p>', 'the empty-state message');
	// Translation calls become their (escaped) English text.
	html = html.replace(new RegExp('<\\?php (?:esc_html_e|esc_attr_e)\\(' + phpString + '\\); \\?>', 'g'), (match, text) => escape(unquote(text)));
	const leftover = html.match(/<\?php[\s\S]*?\?>/);
	if (leftover) throw new Error('shortcode-template.php: unsupported PHP for the standalone page: ' + leftover[0] + '\nUpdate tools/build-standalone.cjs to handle it.');
	return html.trim();
}

function build() {
	return read('standalone/page-template.html')
		.replace(/<!-- Edit this file[\s\S]*?-->\n/, '<!-- Generated by tools/build-standalone.cjs. Edit standalone/page-template.html or shortcode-template.php instead. -->\n')
		.replace('{{player}}', player)
		.replace(/\{\{hash:([^}]+)\}\}/g, (match, file) => crypto.createHash('sha1').update(fs.readFileSync(path.join(root, file))).digest('hex').slice(0, 10));
}

const html = build();
const target = path.join(root, output);
const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
if (process.argv.includes('--check')) {
	if (current !== html) {
		console.error(output + ' is out of date. Run: node tools/build-standalone.cjs');
		process.exit(1);
	}
	console.log(output + ' is up to date.');
} else if (current !== html) {
	fs.writeFileSync(target, html);
	console.log('Updated ' + output + '.');
}
